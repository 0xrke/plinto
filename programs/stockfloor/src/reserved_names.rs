/// Bidi controls. A name or symbol holding one is reserved outright: an override such as U+202E
/// reorders the glyphs on screen ("\u{202E}OTNILP" renders as "PLINTO"), so the logical-order
/// skeleton would not see what viewers see. No token name needs them.
fn is_bidi_control(cp: u32) -> bool {
    matches!(cp, 0x061C | 0x200E | 0x200F | 0x202A..=0x202E | 0x2066..=0x2069)
}

/// The arithmetic rules for whole blocks of styled Latin letters and digits (left out of the table).
fn fold_by_rule(cp: u32) -> Option<u8> {
    // Fullwidth ASCII variants: U+FF01 + k -> 0x21 + k.
    if (0xFF01..=0xFF5E).contains(&cp) {
        return Some((cp - 0xFF01 + 0x21) as u8);
    }
    // Parenthesized ⒜..⒵, circled Ⓐ..Ⓩ and ⓐ..ⓩ.
    if (0x249C..=0x24B5).contains(&cp) {
        return Some(b'a' + (cp - 0x249C) as u8);
    }
    if (0x24B6..=0x24CF).contains(&cp) {
        return Some(b'A' + (cp - 0x24B6) as u8);
    }
    if (0x24D0..=0x24E9).contains(&cp) {
        return Some(b'a' + (cp - 0x24D0) as u8);
    }
    // Squared, negative circled and negative squared capitals: three blocks of A..Z, 32 apart.
    if (0x1F130..=0x1F189).contains(&cp) && (cp - 0x1F130) % 32 < 26 {
        return Some(b'A' + ((cp - 0x1F130) % 32) as u8);
    }
    // Mathematical alphanumeric Latin letters: 13 styles of A..Z then a..z (52 each).
    if (0x1D400..=0x1D6A3).contains(&cp) {
        let k = ((cp - 0x1D400) % 52) as u8;
        return Some(if k < 26 { b'A' + k } else { b'a' + (k - 26) });
    }
    // Mathematical digits: 5 styles of 0..9.
    if (0x1D7CE..=0x1D7FF).contains(&cp) {
        return Some(b'0' + ((cp - 0x1D7CE) % 10) as u8);
    }
    None
}

/// Maps one code point to an ASCII byte, or `None` when it is dropped.
fn fold_to_ascii(cp: u32) -> Option<u8> {
    if cp < 0x80 {
        return Some(cp as u8);
    }
    if let Some(b) = fold_by_rule(cp) {
        return Some(b);
    }
    CONFUSABLES
        .binary_search_by(|(first, last, _)| {
            if *last < cp {
                core::cmp::Ordering::Less
            } else if *first > cp {
                core::cmp::Ordering::Greater
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .ok()
        .map(|i| CONFUSABLES[i].2)
}

/// The ASCII rule: letters lowercase, the l-class {i, l, 1, |, !} to `l`, `0` to `o`, other digits
/// kept, everything else dropped.
fn ascii_skeleton_byte(c: u8) -> Option<u8> {
    let c = match c {
        b'A'..=b'Z' => c + 0x20,
        b'a'..=b'z' | b'0'..=b'9' | b'|' | b'!' => c,
        _ => return None,
    };
    Some(match c {
        b'i' | b'1' | b'|' | b'!' => b'l',
        b'0' => b'o',
        _ => c,
    })
}

/// Calls `f` with each code point of the lossily decoded UTF-8 `bytes`, in order.
fn for_each_char(bytes: &[u8], mut f: impl FnMut(u32)) {
    let mut rest = bytes;
    while !rest.is_empty() {
        let (valid, skip) = match core::str::from_utf8(rest) {
            Ok(s) => (s, rest.len()),
            Err(e) => {
                let n = e.valid_up_to();
                // `valid_up_to` marks a valid prefix, so this cannot fail.
                let s = core::str::from_utf8(&rest[..n]).unwrap_or_default();
                // Drop the maximal invalid subpart (or a truncated sequence at the end).
                (s, n + e.error_len().unwrap_or(rest.len() - n))
            }
        };
        for ch in valid.chars() {
            f(ch as u32);
        }
        rest = &rest[skip..];
    }
}

/// Skeleton byte of one code point, or `None` when it is dropped.
fn skeleton_byte(cp: u32) -> Option<u8> {
    fold_to_ascii(cp).and_then(ascii_skeleton_byte)
}

/// True when the skeleton of `bytes` contains `pllnt`. Streams with a 5-byte window, no buffer.
pub fn skeleton_contains_reserved(bytes: &[u8]) -> bool {
    field_scan(bytes, false)
}

/// True when one field (name or symbol) is reserved: its skeleton contains `pllnt`, or it holds a
/// bidi control.
pub fn field_is_reserved(bytes: &[u8]) -> bool {
    field_scan(bytes, true)
}

fn field_scan(bytes: &[u8], bidi_reserved: bool) -> bool {
    let mut window = [0u8; 5];
    let mut len = 0usize;
    let mut hit = false;
    for_each_char(bytes, |cp| {
        if hit {
            return;
        }
        if bidi_reserved && is_bidi_control(cp) {
            hit = true;
            return;
        }
        let Some(b) = skeleton_byte(cp) else { return };
        if len < window.len() {
            window[len] = b;
            len += 1;
        } else {
            window.copy_within(1.., 0);
            window[4] = b;
        }
        hit = len == window.len() && &window == RESERVED_SKELETON;
    });
    hit
}

/// True when the name or the symbol (raw UTF-8 bytes, padding allowed) imitates the platform brand.
pub fn is_reserved_token_name(name: &[u8], symbol: &[u8]) -> bool {
    field_is_reserved(name) || field_is_reserved(symbol)
}

/// The raw name and symbol fields of a Metaplex `MetadataV1` account for `mint`, or `None` when
/// the data is not one (wrong key byte, another mint, a length prefix beyond the Metaplex maximum or
/// beyond the data). Layout: key (1), update authority (32), mint (32), then the borsh strings name
/// and symbol (u32 LE length + bytes, `\0`-padded by Metaplex). The fields are returned as stored,
/// padding included; the skeleton drops it.
pub fn metadata_name_and_symbol<'a>(
    data: &'a [u8],
    mint: &anchor_lang::prelude::Pubkey,
) -> Option<(&'a [u8], &'a [u8])> {
    use crate::constants::external::{
        METADATA_KEY_V1, METADATA_MAX_NAME_LEN, METADATA_MAX_SYMBOL_LEN,
    };
    if *data.first()? != METADATA_KEY_V1 || data.get(33..65)? != mint.as_ref() {
        return None;
    }
    let (name, rest) = borsh_str(data.get(65..)?, METADATA_MAX_NAME_LEN)?;
    let (symbol, _) = borsh_str(rest, METADATA_MAX_SYMBOL_LEN)?;
    Some((name, symbol))
}

/// Splits a borsh `String` (u32 LE length + bytes) of at most `max` bytes off the front of `data`.
fn borsh_str(data: &[u8], max: usize) -> Option<(&[u8], &[u8])> {
    let len = u32::from_le_bytes(data.get(..4)?.try_into().ok()?) as usize;
    if len > max {
        return None;
    }
    let body = data.get(4..4 + len)?;
    Some((body, &data[4 + len..]))
}

