    #[test]
    fn confusables_are_sorted_and_disjoint() {
        for (first, last, ascii) in CONFUSABLES {
            assert!(first <= last && *first >= 0x80 && ascii.is_ascii_alphanumeric());
            // Already folded by the ASCII rule, and never shadowed by a block rule.
            assert_eq!(ascii_skeleton_byte(*ascii), Some(*ascii));
            assert!(fold_by_rule(*first).is_none() && fold_by_rule(*last).is_none());
            assert!(!(*first..=*last).any(is_bidi_control));
        }
        for w in CONFUSABLES.windows(2) {
            assert!(
                w[0].1 < w[1].0,
                "{:x?} overlaps or precedes {:x?}",
                w[0],
                w[1]
            );
        }
        // Every code point of every range, and the neighbours of each range, resolve as listed.
        for (first, last, ascii) in CONFUSABLES {
            for cp in *first..=*last {
                assert_eq!(fold_to_ascii(cp), Some(*ascii), "U+{cp:04X}");
            }
            for cp in [first - 1, last + 1] {
                if cp >= 0x80
                    && fold_by_rule(cp).is_none()
                    && !CONFUSABLES.iter().any(|(f, l, _)| (*f..=*l).contains(&cp))
                {
                    assert_eq!(fold_to_ascii(cp), None, "U+{cp:04X}");
                }
            }
        }
    }

    #[test]
    fn invalid_utf8_is_decoded_lossily() {
        // Invalid bytes are dropped; the ASCII letters around them still form a hit.
        assert!(is_reserved_token_name(b"PL\xffINTO", b""));
        assert!(is_reserved_token_name(b"", b"PLI\xc3NT"));
        assert!(is_reserved_token_name(b"\xe2\x82PLINTO\xf0", b""));
        // A truncated sequence at the end, or a stray lead byte, alone is not reserved.
        assert!(!is_reserved_token_name(b"\xc3", b"\xff\xfe"));
        assert_eq!(token_name_skeleton(b"Ab\xc3"), "ab");
        // An interior NUL (Metaplex keeps it) is dropped like any ASCII separator.
        assert!(is_reserved_token_name(b"PLI\0NTO", b""));
    }

    #[test]
    fn bidi_controls_reserve_the_field() {
        for c in [
            '\u{061C}', '\u{200E}', '\u{200F}', '\u{202A}', '\u{202E}', '\u{2066}', '\u{2069}',
        ] {
            let field = format!("Coin{c}");
            assert!(is_reserved_token_name(field.as_bytes(), b"OK"), "{c:?}");
            assert!(is_reserved_token_name(b"OK", field.as_bytes()), "{c:?}");
            // The skeleton itself drops them.
            assert_eq!(token_name_skeleton(field.as_bytes()), "coln");
            assert!(!skeleton_contains_reserved(field.as_bytes()));
        }
        // Rendered right to left, this reads PLINTO.
        assert!(is_reserved_token_name("\u{202E}OTNILP".as_bytes(), b""));
        assert!(!is_reserved_token_name("Coin\u{200B}".as_bytes(), b""));
    }

