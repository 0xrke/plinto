//! Reserved token names: no launch may register a token whose name or symbol imitates the platform
//! brand "Plinto" (PLINTO, PLINTA, PL1NT0, "P L I N T O", Cyrillic or Greek look-alikes, fullwidth
//! forms, zero-width characters inside, ...).
//!
//! Every Unicode scalar value is folded through a fixed confusables table to a lowercase ASCII
//! "skeleton"; a token is reserved when the skeleton of its name or of its symbol contains `pllnt`
//! (the skeleton of "plint"), or when the field holds a bidi control (which can reorder glyphs on
//! screen). Words like "splinter" are blocked too; that collateral is accepted.
//!
//! This is a byte-for-byte mirror of `packages/sdk/src/reservedNames.ts`. Both implementations run
//! the shared vectors in `packages/sdk/test/fixtures/{reserved-names,name-skeletons}.json`, so a
//! change to the table must be made in both places, in the same commit.
//!
//! The input is raw Metaplex metadata bytes. Invalid UTF-8 is decoded lossily (each maximal invalid
//! subpart is dropped, like `TextDecoder` replacing it with U+FFFD, which is dropped too), and the
//! `\0` padding Metaplex appends is an ASCII non-alphanumeric and is dropped. Nothing allocates.

/// Skeleton of "plint": the l-class folds `i` into `l`.
pub const RESERVED_SKELETON: &[u8; 5] = b"pllnt";

