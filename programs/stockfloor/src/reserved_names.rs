    fn metadata(mint: &[u8; 32], name: &[u8], symbol: &[u8]) -> Vec<u8> {
        let mut d = vec![4u8];
        d.extend_from_slice(&[0u8; 32]);
        d.extend_from_slice(mint);
        for (field, max) in [(name, NAME_FIELD), (symbol, SYMBOL_FIELD)] {
            let mut f = field.to_vec();
            if f.len() < max {
                f.resize(max, 0);
            }
            d.extend_from_slice(&(f.len() as u32).to_le_bytes());
            d.extend_from_slice(&f);
        }
        d.extend_from_slice(&200u32.to_le_bytes());
        d.extend_from_slice(&[0u8; 200]);
        d
    }

    #[test]
    fn parses_metaplex_metadata_v1() {
        use anchor_lang::prelude::Pubkey;
        let mint = Pubkey::new_from_array([7; 32]);
        let d = metadata(&[7; 32], b"Ab", b"AB");
        let (name, symbol) = metadata_name_and_symbol(&d, &mint).unwrap();
        assert_eq!(name.len(), NAME_FIELD);
        assert_eq!(&name[..3], b"Ab\0");
        assert_eq!(symbol.len(), SYMBOL_FIELD);
        assert!(!is_reserved_token_name(name, symbol));

        let d = metadata(&[7; 32], "ＰＬＩＮＴＯ".as_bytes(), b"X");
        let (name, symbol) = metadata_name_and_symbol(&d, &mint).unwrap();
        assert!(is_reserved_token_name(name, symbol));

        // Full-length fields are stored unpadded.
        let d = metadata(&[7; 32], &[b'A'; 32], b"PLINT\0\0\0\0\0");
        let (name, symbol) = metadata_name_and_symbol(&d, &mint).unwrap();
        assert_eq!((name.len(), symbol.len()), (32, 10));
        assert!(is_reserved_token_name(name, symbol));
    }

    #[test]
    fn rejects_malformed_metadata() {
        use anchor_lang::prelude::Pubkey;
        let mint = Pubkey::new_from_array([7; 32]);
        let good = metadata(&[7; 32], b"Ab", b"AB");
        assert!(metadata_name_and_symbol(&good, &mint).is_some());
        // Another mint.
        assert!(metadata_name_and_symbol(&good, &Pubkey::new_from_array([8; 32])).is_none());
        // Wrong key byte (e.g. an edition or an uninitialized account).
        let mut d = good.clone();
        d[0] = 6;
        assert!(metadata_name_and_symbol(&d, &mint).is_none());
        d[0] = 0;
        assert!(metadata_name_and_symbol(&d, &mint).is_none());
        // Name length beyond the Metaplex maximum, or beyond the data.
        let mut d = good.clone();
        d[65..69].copy_from_slice(&33u32.to_le_bytes());
        assert!(metadata_name_and_symbol(&d, &mint).is_none());
        let mut d = good.clone();
        d[65..69].copy_from_slice(&u32::MAX.to_le_bytes());
        assert!(metadata_name_and_symbol(&d, &mint).is_none());
        // Symbol length beyond the Metaplex maximum.
        let mut d = good.clone();
        d[101..105].copy_from_slice(&11u32.to_le_bytes());
        assert!(metadata_name_and_symbol(&d, &mint).is_none());
        // Truncated data at every length.
        for n in 0..(1 + 32 + 32 + 4 + 32 + 4 + 10) {
            assert!(
                metadata_name_and_symbol(&good[..n], &mint).is_none(),
                "len {n}"
            );
        }
        assert!(metadata_name_and_symbol(&good[..115], &mint).is_some());
        assert!(metadata_name_and_symbol(&[], &mint).is_none());
    }

    proptest! {
        /// Dropped content (unknown characters, invalid bytes) inserted between the letters never
        /// breaks an ASCII hit: dropping only joins neighbours.
        #[test]
        fn noise_never_breaks_an_ascii_hit(
            noise in proptest::collection::vec(
                prop_oneof![
                    Just(&b"\xff"[..]),
                    Just(&b"\xc3"[..]),
                    Just(&b"\xe2\x80\x8b"[..]), // U+200B zero-width space
                    Just(&b"\xf0\x9f\x9a\x80"[..]), // U+1F680 rocket
                    Just(&b" "[..]),
                    Just(&b"\0"[..]),
                    Just(&b"-"[..]),
                ],
                0..6,
            ),
            positions in proptest::collection::vec(0usize..7, 0..6),
        ) {
            let letters = b"PLINTO";
            let mut out = Vec::new();
            for (i, letter) in letters.iter().enumerate() {
                for (n, p) in noise.iter().zip(positions.iter()) {
                    if *p == i {
                        out.extend_from_slice(n);
                    }
                }
                out.push(*letter);
            }
            prop_assert!(is_reserved_token_name(&out, b""));
            prop_assert!(is_reserved_token_name(b"", &out));
        }

        /// The skeleton only ever holds lowercase letters other than `i`, and digits other than
        /// 0 and 1; the streaming check agrees with the materialised skeleton.
        #[test]
        fn skeleton_alphabet_and_streaming_agree(bytes in proptest::collection::vec(any::<u8>(), 0..48)) {
            let s = token_name_skeleton(&bytes);
            prop_assert!(s.bytes().all(|b| matches!(b, b'a'..=b'h' | b'j'..=b'z' | b'2'..=b'9')));
            prop_assert_eq!(skeleton_contains_reserved(&bytes), s.contains("pllnt"));
        }

        /// Skeletons are fixed points.
        #[test]
        fn skeleton_is_idempotent(s in "\\PC{0,16}") {
            let once = token_name_skeleton(s.as_bytes());
            prop_assert_eq!(token_name_skeleton(once.as_bytes()), once);
        }
    }
