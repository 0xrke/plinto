/**
 * Reserved token names: nobody may launch a token whose name or ticker imitates the platform brand
 * "Plinto" (PLINTO, PLINTA, PL1NT0, "P L I N T O", Cyrillic or Greek look-alikes, fullwidth forms,
 * zero-width characters inside, ...).
 *
 * The rule maps every Unicode scalar value through a fixed confusables table to a lowercase ASCII
 * "skeleton" and blocks the token when the skeleton of the name or of the symbol contains "pllnt"
 * (the skeleton of "plint"), or when either holds a bidi control (which can reorder glyphs on screen).
 * Words like "splinter" are blocked too; that collateral is accepted.
 *
 * The program enforces the same rule on chain (programs/stockfloor). Both implementations run the
 * shared vectors in packages/sdk/test/fixtures/{reserved-names,name-skeletons}.json, so any change to
 * the table here must be made there too, in the same commit.
 */

