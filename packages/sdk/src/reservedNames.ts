/**
 * Bidi controls. A name or ticker holding one is reserved outright: an override such as U+202E
 * reorders the glyphs on screen ("\u202EOTNILP" renders as "PLINTO"), so the logical-order skeleton
 * would not see what viewers see.
 */
const BIDI_CONTROL = /[\u061C\u200E\u200F\u202A-\u202E\u2066-\u2069]/;

/** The arithmetic rules for whole blocks of styled Latin letters and digits (left out of the table). */
function foldByRule(cp: number): number | undefined {
  // Fullwidth ASCII variants: U+FF01 + k -> 0x21 + k.
  if (cp >= 0xff01 && cp <= 0xff5e) return cp - 0xff01 + 0x21;
  // Parenthesized ⒜..⒵, circled Ⓐ..Ⓩ and ⓐ..ⓩ.
  if (cp >= 0x249c && cp <= 0x24b5) return 0x61 + (cp - 0x249c);
  if (cp >= 0x24b6 && cp <= 0x24cf) return 0x41 + (cp - 0x24b6);
  if (cp >= 0x24d0 && cp <= 0x24e9) return 0x61 + (cp - 0x24d0);
  // Squared, negative circled and negative squared capitals: three blocks of A..Z, 32 apart.
  if (cp >= 0x1f130 && cp <= 0x1f189 && (cp - 0x1f130) % 32 < 26) return 0x41 + ((cp - 0x1f130) % 32);
  // Mathematical alphanumeric Latin letters: 13 styles of A..Z then a..z (52 each).
  if (cp >= 0x1d400 && cp <= 0x1d6a3) {
    const k = (cp - 0x1d400) % 52;
    return k < 26 ? 0x41 + k : 0x61 + (k - 26);
  }
  // Mathematical digits: 5 styles of 0..9.
  if (cp >= 0x1d7ce && cp <= 0x1d7ff) return 0x30 + ((cp - 0x1d7ce) % 10);
  return undefined;
}

/** Maps one code point to an ASCII code point, or undefined when it is dropped. */
function foldToAscii(cp: number): number | undefined {
  if (cp < 0x80) return cp;
  const ruled = foldByRule(cp);
  if (ruled !== undefined) return ruled;
  let lo = 0;
  let hi = CONFUSABLES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [first, last, ascii] = CONFUSABLES[mid];
    if (last < cp) lo = mid + 1;
    else if (first > cp) hi = mid - 1;
    else return ascii.charCodeAt(0);
  }
  return undefined;
}

/** The ASCII rule: letters lowercase, the l-class {i, l, 1, |, !} to l, 0 to o, other digits kept, rest dropped. */
function asciiSkeletonChar(c: number): string {
  let ch: string;
  if (c >= 0x41 && c <= 0x5a) ch = String.fromCharCode(c + 0x20);
  else if ((c >= 0x61 && c <= 0x7a) || (c >= 0x30 && c <= 0x39) || c === 0x7c || c === 0x21) ch = String.fromCharCode(c);
  else return "";
  if (ch === "i" || ch === "1" || ch === "|" || ch === "!") return "l";
  if (ch === "0") return "o";
  return ch;
}

/** Lowercase ASCII skeleton of a token name or symbol (see the module comment). */
export function tokenNameSkeleton(s: string): string {
  let out = "";
  for (const ch of s) {
    const ascii = foldToAscii(ch.codePointAt(0)!);
    if (ascii !== undefined) out += asciiSkeletonChar(ascii);
  }
  return out;
}

/** True when the name or the symbol imitates the platform brand and must not be launched. */
export function isReservedTokenName(name: string, symbol: string): boolean {
  return [name, symbol].some((s) => BIDI_CONTROL.test(s) || tokenNameSkeleton(s).includes(RESERVED_SKELETON));
}
