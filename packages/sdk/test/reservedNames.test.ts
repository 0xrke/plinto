/**
 * Reserved token names: the shared vectors in test/fixtures are the contract with the program's Rust
 * implementation (programs/stockfloor reads the same files with include_str!), so both sides must agree.
 */
import fc from "fast-check";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { isReservedTokenName, RESERVED_NAME_MESSAGE, tokenNameSkeleton } from "../src";
import { CONFUSABLES } from "../src/reservedNames";

interface ReservedVector {
  name: string;
  symbol: string;
  reserved: boolean;
}

interface SkeletonVector {
  input: string;
  skeleton: string;
}

const fixture = <T>(file: string): T => JSON.parse(readFileSync(join(__dirname, "fixtures", file), "utf8")) as T;

const RESERVED_VECTORS = fixture<ReservedVector[]>("reserved-names.json");
const SKELETON_VECTORS = fixture<SkeletonVector[]>("name-skeletons.json");

describe("reserved-name vectors", () => {
  it("has enough positive and negative vectors", () => {
    expect(RESERVED_VECTORS.length).toBeGreaterThanOrEqual(40);
    expect(RESERVED_VECTORS.filter((v) => v.reserved).length).toBeGreaterThanOrEqual(20);
    expect(RESERVED_VECTORS.filter((v) => !v.reserved).length).toBeGreaterThanOrEqual(20);
  });

  it.each(RESERVED_VECTORS.map((v) => [JSON.stringify(v.name), JSON.stringify(v.symbol), v] as const))(
    "name %s symbol %s",
    (_n, _s, v) => {
      expect(isReservedTokenName(v.name, v.symbol)).toBe(v.reserved);
    },
  );
});

describe("tokenNameSkeleton", () => {
  it.each(SKELETON_VECTORS.map((v) => [JSON.stringify(v.input), v] as const))("skeleton of %s", (_i, v) => {
    expect(tokenNameSkeleton(v.input)).toBe(v.skeleton);
  });

  it("only ever emits lowercase ASCII letters and digits other than 0 and 1, without i", () => {
    fc.assert(
      fc.property(fc.fullUnicodeString({ maxLength: 40 }), (s) => {
        expect(tokenNameSkeleton(s)).toMatch(/^[a-hj-z2-9]*$/);
      }),
    );
  });

  it("is idempotent", () => {
    fc.assert(
      fc.property(fc.fullUnicodeString({ maxLength: 40 }), (s) => {
        const sk = tokenNameSkeleton(s);
        expect(tokenNameSkeleton(sk)).toBe(sk);
      }),
    );
  });

  it("ignores ASCII case", () => {
    fc.assert(
      fc.property(fc.asciiString({ maxLength: 40 }), (s) => {
        expect(tokenNameSkeleton(s.toUpperCase())).toBe(tokenNameSkeleton(s.toLowerCase()));
      }),
    );
  });

  it("is not defeated by inserting invisible characters anywhere", () => {
    const invisible = fc.constantFrom("​", "‌", "‍", "⁠", "﻿", "­", "️", "́", " ", "-", "_", ".");
    fc.assert(
      fc.property(fc.array(fc.array(invisible, { maxLength: 3 }), { minLength: 7, maxLength: 7 }), (fill) => {
        const letters = ["P", "l", "i", "n", "t", "o"];
        const name = letters.map((c, k) => fill[k].join("") + c).join("") + fill[6].join("");
        expect(isReservedTokenName(name, "")).toBe(true);
        expect(isReservedTokenName("", name)).toBe(true);
      }),
    );
  });
});

describe("confusables table", () => {
  it("is identical to the program's table (both generated by scripts/gen-reserved-confusables.py)", () => {
    const rust = readFileSync(join(__dirname, "../../../programs/stockfloor/src/reserved_names.rs"), "utf8");
    const block = rust.slice(rust.indexOf("// BEGIN GENERATED CONFUSABLES"), rust.indexOf("// END GENERATED CONFUSABLES"));
    const rows = [...block.matchAll(/^\s*\(0x([0-9A-F]+), 0x([0-9A-F]+), b'(.)'\),/gm)].map(
      (m) => [parseInt(m[1], 16), parseInt(m[2], 16), m[3]] as const,
    );
    expect(rows.length).toBeGreaterThan(100);
    expect(rows).toEqual(CONFUSABLES.map((r) => [...r]));
  });

  it("is sorted and disjoint, so the binary search is valid", () => {
    for (let k = 0; k < CONFUSABLES.length; k++) {
      const [first, last, out] = CONFUSABLES[k];
      expect(first).toBeLessThanOrEqual(last);
      expect(out).toMatch(/^[a-hj-z2-9]$/);
      if (k > 0) expect(CONFUSABLES[k - 1][1]).toBeLessThan(first);
    }
  });
});

describe("isReservedTokenName", () => {
  it("reserves any name or ticker holding a bidi control", () => {
    for (const c of ["\u061c", "\u200e", "\u200f", "\u202a", "\u202e", "\u2066", "\u2069"]) {
      expect(isReservedTokenName(`Coin${c}`, "OK")).toBe(true);
      expect(isReservedTokenName("Coin", `${c}OK`)).toBe(true);
    }
    // Rendered right to left, this reads PLINTO.
    expect(isReservedTokenName("\u202eOTNILP", "")).toBe(true);
  });

  it("checks the name and the symbol independently", () => {
    expect(isReservedTokenName("Plinto", "OK")).toBe(true);
    expect(isReservedTokenName("OK", "Plinto")).toBe(true);
    // Split across the two fields is not a hit.
    expect(isReservedTokenName("Pli", "nto")).toBe(false);
  });

  it("exposes a short UI message", () => {
    expect(RESERVED_NAME_MESSAGE).toBe('Names and tickers that look like "Plinto" are reserved.');
  });
});
